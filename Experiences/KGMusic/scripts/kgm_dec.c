static uint32_t le32(const uint8_t* b) {
    return b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24);
}

static const char* sniff(const uint8_t* d, size_t n) {
    if (n >= 4 && d[0] == 'f' && d[1] == 'L' && d[2] == 'a' && d[3] == 'C') return "flac";
    if (n >= 3 && d[0] == 'I' && d[1] == 'D' && d[2] == '3') return "mp3";
    if (n >= 4 && d[0] == 'O' && d[1] == 'g' && d[2] == 'g' && d[3] == 'S') return "ogg";
    return NULL;
}

static int decrypt_one(const char* src, const char* dst) {
    FILE* f = fopen(src, "rb");
    if (!f) return -1;
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t* buf = (uint8_t*)malloc(size);
    if (!buf) { fclose(f); return -1; }
    fread(buf, 1, size, f);
    fclose(f);
    if (size < 0x400) { free(buf); return -1; }

    uint32_t audio_offset = le32(buf + 0x10);
    uint8_t key[17] = {0};
    memcpy(key, buf + 0x1C, 16);

    uint64_t len = size - audio_offset;
    uint8_t* audio = buf + audio_offset;
    for (uint64_t pos = 0; pos < len; pos++) {
        uint8_t med8 = key[pos % 17] ^ audio[pos];
        med8 ^= (med8 & 15) << 4;
        uint8_t msk8 = 0;
        uint32_t offset = (uint32_t)(pos >> 4);
        while (offset >= 0x11) {
            msk8 ^= table1[offset % 272];
            offset >>= 4;
            msk8 ^= table2[offset % 272];
            offset >>= 4;
        }
        msk8 = MaskV2PreDef[pos % 272] ^ msk8;
        msk8 ^= (msk8 & 15) << 4;
        audio[pos] = med8 ^ msk8;
    }

    const char* ext = sniff(audio, len);
    if (!ext) { free(buf); return -2; }
    FILE* o = fopen(dst, "wb");
    if (!o) { free(buf); return -1; }
    fwrite(audio, 1, len, o);
    fclose(o);
    free(buf);
    return 0;
}

static void walk(const char* srcdir, const char* outdir) {
    char pat[2048];
    struct dirent* e;
    DIR* d = opendir(srcdir);
    if (!d) return;
    while ((e = readdir(d)) != NULL) {
        char path[2048];
        if (strcmp(e->d_name, ".") == 0 || strcmp(e->d_name, "..") == 0) continue;
        snprintf(path, sizeof(path), "%s\\%s", srcdir, e->d_name);
        struct stat st;
        if (stat(path, &st) == 0 && (st.st_mode & S_IFDIR)) {
            char sub[2048];
            snprintf(sub, sizeof(sub), "%s\\%s", outdir, e->d_name);
            mkdir(sub);
            walk(path, sub);
        } else {
            const char* dot = strrchr(e->d_name, '.');
            if (!dot) continue;
            if (_stricmp(dot, ".kgma") != 0 && _stricmp(dot, ".kgm") != 0) continue;
            char base[1024];
            size_t bl = dot - e->d_name;
            memcpy(base, e->d_name, bl);
            base[bl] = 0;
            char dst[2048];
            snprintf(dst, sizeof(dst), "%s\\%s.out", outdir, base);
            int r = decrypt_one(path, dst);
            if (r != 0) {
                printf("FAIL %s (%d)\n", e->d_name, r);
                remove(dst);
                continue;
            }
            /* 探测扩展名 */
            FILE* o = fopen(dst, "rb");
            unsigned char hdr[8] = {0};
            if (o) { fread(hdr, 1, 8, o); fclose(o); }
            const char* ext = sniff(hdr, 8);
            char final[2048];
            snprintf(final, sizeof(final), "%s\\%s.%s", outdir, base, ext);
            rename(dst, final);
            printf("OK   %s -> .%s\n", e->d_name, ext);
        }
    }
    closedir(d);
}

int main(int argc, char** argv) {
    if (argc < 3) { printf("usage: kgm_dec.exe <indir> <outdir>\n"); return 1; }
    mkdir(argv[2]);
    walk(argv[1], argv[2]);
    return 0;
}
